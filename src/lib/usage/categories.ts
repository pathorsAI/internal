export const TOOL_CATEGORY: Readonly<Record<string, FeatureCategory>> = Object.fromEntries(
  FEATURE_CATEGORIES.flatMap((category) => BY_CATEGORY[category].map((tool) => [tool, category])),
);

/** 測試用：同一支工具被列在兩個分類底下。 */
export function duplicateToolCategories(): string[] {
  const seen = new Set<string>();
  const dup: string[] = [];
  for (const c of FEATURE_CATEGORIES) {
    for (const tool of BY_CATEGORY[c]) {
      if (seen.has(tool)) dup.push(tool);
      seen.add(tool);
    }
  }
  return dup;
}

export function categoryOf(kind: "page" | "tool", feature: string): FeatureCategory | null {
  if (kind === "page") return PAGE_CATEGORY[feature as DashboardRoute] ?? null;
  return TOOL_CATEGORY[feature] ?? null;
}
